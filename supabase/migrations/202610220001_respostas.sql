-- Execute no SQL Editor do projeto Supabase antes de publicar o histórico.
-- A transação é repetível e não remove registros existentes.
begin;

create table if not exists public.respostas (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id),
  entrada text not null,
  resposta text not null,
  created_at timestamptz not null default now()
);

-- Compatibilidade com uma tabela respostas já criada durante o curso.
alter table public.respostas
  add column if not exists user_id uuid references auth.users(id),
  add column if not exists entrada text,
  add column if not exists resposta text,
  add column if not exists created_at timestamptz;

-- Define defaults somente para novos registros, sem inventar dono/data dos antigos.
alter table public.respostas
  alter column user_id set default auth.uid(),
  alter column created_at set default now();

create index if not exists respostas_user_created_at_idx
  on public.respostas (user_id, created_at desc nulls last, id desc);

alter table public.respostas enable row level security;

-- SELECT e INSERT são feitos com a sessão da pessoa, sem chave administrativa.
grant select, insert on public.respostas to authenticated;

-- Tabelas antigas podem usar uma sequence para o id. Libera apenas essa sequence.
do $$
declare
  id_sequence text;
begin
  id_sequence := pg_get_serial_sequence('public.respostas', 'id');
  if id_sequence is not null then
    execute format('grant usage on sequence %s to authenticated', id_sequence);
  end if;
end $$;

drop policy if exists respostas_select_own on public.respostas;
create policy respostas_select_own on public.respostas
  for select to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists respostas_insert_own on public.respostas;
create policy respostas_insert_own on public.respostas
  for insert to authenticated
  with check ((select auth.uid()) = user_id);

-- O limite restritivo também vale se já existir uma policy permissiva antiga.
-- Registros antigos sem user_id não são atribuídos a outra pessoa automaticamente.
drop policy if exists respostas_owner_guard on public.respostas;
create policy respostas_owner_guard on public.respostas
  as restrictive for all to public
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

commit;
